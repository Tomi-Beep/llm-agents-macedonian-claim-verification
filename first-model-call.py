from ollama import chat

prompt = """Провери го тврдењето според дадените докази.
Тврдење: Според Пописот од 2021 година, Северна Македонија имала 2.097.319 резидентни жители.

Докази:
[census-total] Вкупно биле попишани 2.097.319 лица.
[census-residents] Биле попишани 1.836.713 резидентни жители.

Избери една пресуда: поткрепено, противречи на доказите или недоволно докази.
Објасни ја пресудата на македонски и наведи го ID-то на доказот.
"""

reply = chat(
    model="qwen3:4b-instruct-2507-q4_K_M",
    messages=[{"role": "user", "content": prompt}],
)

print(reply.message.content)